"""Pure, bounded delivery policy for existing Jervis ProactiveEngine.

No microphone, network, filesystem scans, LLM suggestions, external data,
transcripts, or notifications are generated by this module.
"""
from __future__ import annotations

import math
import re
import threading
from collections import deque
from dataclasses import dataclass

_EVENT = re.compile(r"[a-z][a-z0-9_.-]{0,79}\Z")
_SEVERITY = {"info": 1, "important": 2, "critical": 3}


@dataclass(frozen=True)
class Candidate:
    event_id: str
    event_code: str
    user_id: str
    severity: str
    created_at: float
    expires_at: float


@dataclass(frozen=True)
class DeliveryContext:
    now: float
    local_minute: int
    is_present: bool
    is_busy: bool
    quiet_start: int = 23 * 60
    quiet_end: int = 7 * 60


@dataclass(frozen=True)
class DeliveryDecision:
    action: str                     # deliver | defer | discard
    reason: str


class DeliveryPolicy:
    def __init__(self, *, cooldown_seconds: float = 300,
                 max_per_hour: int = 12, max_entries: int = 512):
        if not 0 <= cooldown_seconds <= 86400:
            raise ValueError("Invalid notification cooldown")
        if not 1 <= max_per_hour <= 120:
            raise ValueError("Invalid notification rate limit")
        if not 16 <= max_entries <= 4096:
            raise ValueError("Invalid delivery history size")
        self.cooldown_seconds = cooldown_seconds
        self.max_per_hour = max_per_hour
        self._sent: deque[tuple[float, str, str, str]] = deque(maxlen=max_entries)
        self._lock = threading.RLock()

    @staticmethod
    def _quiet(ctx: DeliveryContext) -> bool:
        if not (0 <= ctx.local_minute < 1440 and 0 <= ctx.quiet_start < 1440
                and 0 <= ctx.quiet_end < 1440):
            raise ValueError("Invalid local clock or quiet hours")
        start, end, current = ctx.quiet_start, ctx.quiet_end, ctx.local_minute
        if start == end:
            return False
        return start <= current < end if start < end else (
            current >= start or current < end
        )

    def decide(self, candidate: Candidate, context: DeliveryContext) -> DeliveryDecision:
        if (not isinstance(candidate.event_id, str)
                or not re.fullmatch(r"[0-9a-f]{32}", candidate.event_id)
                or not _EVENT.fullmatch(candidate.event_code)
                or candidate.severity not in _SEVERITY
                or not candidate.user_id or len(candidate.user_id) > 128):
            raise ValueError("Invalid candidate metadata")
        if any(not math.isfinite(x) for x in (
            candidate.created_at, candidate.expires_at, context.now
        )):
            raise ValueError("Invalid event timestamps")
        if candidate.created_at > context.now + 300:
            return DeliveryDecision("defer", "Event timestamp is in the future")
        if candidate.expires_at <= context.now:
            return DeliveryDecision("discard", "Notification expired")
        if not context.is_present:
            return DeliveryDecision("defer", "User is absent")
        if context.is_busy:
            return DeliveryDecision("defer", "User is busy")
        if self._quiet(context) and candidate.severity != "critical":
            return DeliveryDecision("defer", "Quiet hours")
        with self._lock:
            recent = [entry for entry in self._sent
                      if entry[0] > context.now - 3600]
            if any(entry[3] == candidate.event_id for entry in recent):
                return DeliveryDecision("discard", "Event already delivered")
            if candidate.severity != "critical":
                user_recent = [entry for entry in recent if entry[1] == candidate.user_id]
                if len(user_recent) >= self.max_per_hour:
                    return DeliveryDecision("defer", "Rate limit")
                if any(entry[1] == candidate.user_id
                       and entry[2] == candidate.event_code
                       and entry[0] > context.now - self.cooldown_seconds
                       for entry in recent):
                    return DeliveryDecision("defer", "Event cooldown")
        return DeliveryDecision("deliver", "Eligible notification")

    def mark_delivered(self, candidate: Candidate, context: DeliveryContext) -> bool:
        """Call immediately before the actual delivery; no message body is stored."""
        with self._lock:
            if self.decide(candidate, context).action != "deliver":
                return False
            self._sent.append((
                context.now, candidate.user_id, candidate.event_code,
                candidate.event_id,
            ))
            return True
